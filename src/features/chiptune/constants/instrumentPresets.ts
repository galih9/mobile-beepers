/** Looks up retro and modern presets. Unknown ids fall back to the first retro preset. */
export const getPresetConfigurationById = (
	presetId: string
): InstrumentPresetDefinition => {
	return (
		INSTRUMENT_PRESETS.find((preset) => preset.id === presetId) ??
		getModernPresetById(presetId) ??
		INSTRUMENT_PRESETS[0] ??
		FALLBACK_PRESET
	);
};
